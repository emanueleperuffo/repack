import fs from 'node:fs';
import { composeSourceMaps } from './composeSourceMaps.js';
import { transformBundleToHermesBytecode } from './transformBundleToHermesBytecode.js';

/**
 * A single asset to compile to Hermes bytecode.
 */
export interface HermesJob {
  /** Path to the Hermes compiler binary. */
  hermesCLIPath: string;

  /** Path to React-Native package inside node_modules. */
  reactNativePath: string;

  /** Path to the bundle to be transformed. */
  bundlePath: string;
}

/**
 * Result of {@link runHermesJob}.
 */
export interface HermesJobResult {
  /** Whether the bundle had a source map, which was composed with the Hermes one. */
  composedSourceMap: boolean;
}

/**
 * Transforms a bundle to Hermes bytecode and, when the bundle has a source map,
 * composes it with the source map generated by Hermes.
 */
export const runHermesJob = async ({
  hermesCLIPath,
  reactNativePath,
  bundlePath,
}: HermesJob): Promise<HermesJobResult> => {
  const sourceMapPath = `${bundlePath}.map`;
  const useSourceMaps = await fs.promises
    .access(sourceMapPath)
    .then(() => true)
    .catch(() => false);

  const { sourceMap: hermesSourceMapPath } =
    await transformBundleToHermesBytecode({
      hermesCLIPath,
      useSourceMaps,
      bundlePath,
    });

  if (useSourceMaps) {
    await composeSourceMaps({
      reactNativePath,
      packagerMapPath: sourceMapPath,
      compilerMapPath: hermesSourceMapPath,
    });
  }

  return { composedSourceMap: useSourceMaps };
};
